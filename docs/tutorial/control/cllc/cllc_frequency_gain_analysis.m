%% CLLC 正向和反向不同功率下的频率增益分析
% 使用基波近似法（Fundamental Harmonic Approximation, FHA）计算图示
% CLLC 谐振网络在正向、反向功率流下的频率增益曲线。
%
% 默认工况：
%   - 正向功率流：原边 450 V -> 副边 48 V
%   - 反向功率流：副边 48 V -> 原边 450 V
%   - 输入侧全桥驱动，输出侧全桥整流/同步整流
%   - 忽略开关管压降、死区、绕组电阻和磁性元件损耗
%
% 增益定义：
%   G = Vout / Vin
%   正向归一化增益 M_forward = n * G_forward
%   反向归一化增益 M_reverse = G_reverse / n
%   其中 n = Np / Ns
%
% 对全桥整流和恒压输出，输出侧 FHA 等效交流负载为：
%   Rac = 8 / pi^2 * Vout^2 / Pout
%
% 控制环路波特图参考论文 Energies 2023, 16, 7173 的式 (13)-(16)：
%   - 被控对象：Gvf(s) = Delta Vout(s) / Delta fs(s)
%   - 控制器：Gc(s) = Kp + Ki/s
%   - 开环：T(s) = Gc(s) * Gvf(s)
%   - PI 零点设置为目标交越频率的 0.1 倍
%   - 2P2Z：K*(1+s/wz)^2/[s*(1+s/wp)^2]
%     参数 K、fz、fp 与 code/lib/z2p2_init() 的连续原型一致
%
% 论文通过小信号模型和计算机仿真获得功率级。本脚本在缺少实测
% FRA/PLECS AC Sweep 数据时，使用 FHA 稳态增益斜率和输出电容功率
% 平衡建立低频包络近似。该模型适合初步控制器设计，最终参数应由
% PLECS 小信号注入或硬件 FRA 结果校核。

clear;
clc;
close all;

%% 用户可调参数
Vin_forward = 450;                 % 正向输入直流电压 / V
Vout_forward = 48;                 % 正向输出直流电压 / V
Vin_reverse = 48;                  % 反向输入直流电压 / V
Vout_reverse = 450;                % 反向输出直流电压 / V
power_w = [100, 500, 1000, 2000, 3000, ...
           4000, 5000, 6000, 6600]; % 输出功率点 / W

frequency_hz = linspace(20e3, 260e3, 4801); % 计算扫频范围 / Hz
forward_plot_range_hz = [40e3, 260e3];
reverse_plot_range_hz = [20e3, 120e3];

% 调频控制环路参数
Cout_forward = 10000e-6;           % PLECS 正向低压侧输出电容 / F
Cout_reverse = 1360e-6;            % PLECS 反向高压侧输出电容 / F
control_frequency_hz = logspace(-2, 5, 2801); % 环路扰动频率 / Hz
control_plot_range_hz = [0.1, 30e3];
controller_crossover_hz = 3.5e3;  % 论文 PFM 示例交越频率 / Hz
controller_zero_ratio = 0.1;       % fz/fc，来自论文式 (16)
forward_controller_design_power_w = 6600;
reverse_controller_design_power_w = 4000;
control_delay_cycles = 1;          % 调制与数字更新等效延迟 / 开关周期
z2p2_target_phase_margin_deg = 50; % 兼顾 PM 与 GM 的设计点目标
z2p2_target_gain_margin_db = 6;
z2p2_min_crossover_ratio = 0.2;    % 最低搜索到 PI 目标带宽的比例
z2p2_max_pole_fs_ratio = 0.2;      % 高频极点不超过最低工作 fs 的比例

% 图中 CLLC 谐振网络参数
Lr_primary = 40e-6;                % 原边串联谐振电感 / H
Cr_primary = 80e-9;                % 原边串联谐振电容 / F
Lm_primary = 200e-6;               % 原边励磁电感 / H
Lr_secondary = 0.625e-6;           % 副边串联谐振电感 / H
Cr_secondary = 5.12e-6;            % 副边串联谐振电容 / F

Np = 24;                           % 原边匝数
Ns = 3;                            % 副边匝数
n = Np / Ns;                       % 原副边匝数比

%% 正向和反向 FHA 等效负载
Rload_dc_forward = Vout_forward^2 ./ power_w;
Rload_ac_forward = (8 / pi^2) .* Rload_dc_forward;

Rload_dc_reverse = Vout_reverse^2 ./ power_w;
Rload_ac_reverse = (8 / pi^2) .* Rload_dc_reverse;

%% 谐振元件阻抗
omega = 2 * pi * frequency_hz(:);

Zr_primary = 1j .* omega .* Lr_primary + ...
             1 ./ (1j .* omega .* Cr_primary);
Zm_primary = 1j .* omega .* Lm_primary;
Zr_secondary = 1j .* omega .* Lr_secondary + ...
               1 ./ (1j .* omega .* Cr_secondary);

%% 正向频率增益：原边输入，副边输出
% 每一列对应一个输出功率点。副边串联支路折算到原边后，与励磁
% 电感并联。
Zsecondary_total_forward = Zr_secondary + Rload_ac_forward;
Zsecondary_referred_forward = n^2 .* Zsecondary_total_forward;
Zparallel_forward = ...
    (Zm_primary .* Zsecondary_referred_forward) ./ ...
    (Zm_primary + Zsecondary_referred_forward);

% H_primary：原边谐振腔输入到变压器原边端口的传递函数。
% H_secondary：变压器副边端口到 FHA 等效交流负载的传递函数。
H_primary_forward = Zparallel_forward ./ ...
                    (Zr_primary + Zparallel_forward);
H_secondary_forward = Rload_ac_forward ./ ...
                      Zsecondary_total_forward;
H_vout_vin_forward = ...
    H_primary_forward .* H_secondary_forward ./ n;

gain_dc_forward = abs(H_vout_vin_forward);
gain_normalized_forward = n .* gain_dc_forward;

%% 反向频率增益：副边输入，原边输出
% 原边输出负载与原边谐振支路串联，该支路与励磁电感并联后再折算
% 到副边。励磁电感始终位于物理原边，反向增益不能由正向增益直接
% 取倒数得到。
Zprimary_total_reverse = Zr_primary + Rload_ac_reverse;
Zparallel_primary_reverse = ...
    (Zm_primary .* Zprimary_total_reverse) ./ ...
    (Zm_primary + Zprimary_total_reverse);
Zparallel_referred_secondary_reverse = ...
    Zparallel_primary_reverse ./ n^2;

H_secondary_reverse = Zparallel_referred_secondary_reverse ./ ...
    (Zr_secondary + Zparallel_referred_secondary_reverse);
H_primary_reverse = Rload_ac_reverse ./ Zprimary_total_reverse;
H_vout_vin_reverse = ...
    H_secondary_reverse .* H_primary_reverse .* n;

gain_dc_reverse = abs(H_vout_vin_reverse);
gain_normalized_reverse = gain_dc_reverse ./ n;

%% 特征频率与目标增益
fr_primary_hz = 1 / (2 * pi * sqrt(Lr_primary * Cr_primary));
fr_secondary_hz = 1 / (2 * pi * sqrt(Lr_secondary * Cr_secondary));

target_gain_dc_forward = Vout_forward / Vin_forward;
target_gain_normalized_forward = n * target_gain_dc_forward;
target_gain_dc_reverse = Vout_reverse / Vin_reverse;
target_gain_normalized_reverse = target_gain_dc_reverse / n;

frequency_forward_hz = nan(size(power_w));
frequency_reverse_hz = nan(size(power_w));
for k = 1:numel(power_w)
    frequency_forward_hz(k) = find_gain_crossing( ...
        frequency_hz, gain_normalized_forward(:, k), ...
        target_gain_normalized_forward, fr_primary_hz, 'above');
    frequency_reverse_hz(k) = find_gain_crossing( ...
        frequency_hz, gain_normalized_reverse(:, k), ...
        target_gain_normalized_reverse, fr_primary_hz, 'below');
end

[max_gain_reverse, max_gain_reverse_index] = ...
    max(gain_normalized_reverse, [], 1);
max_gain_reverse_frequency_hz = ...
    frequency_hz(max_gain_reverse_index);

operating_points_forward = table( ...
    power_w(:), Rload_dc_forward(:), Rload_ac_forward(:), ...
    frequency_forward_hz(:) / 1e3, ...
    'VariableNames', { ...
        'Power_W', 'RloadDC_Ohm', 'RloadAC_Ohm', ...
        'FrequencyAboveResonance_kHz'});

operating_points_reverse = table( ...
    power_w(:), Rload_dc_reverse(:), Rload_ac_reverse(:), ...
    max_gain_reverse(:), max_gain_reverse_frequency_hz(:) / 1e3, ...
    frequency_reverse_hz(:) / 1e3, ...
    'VariableNames', { ...
        'Power_W', 'RloadDC_Ohm', 'RloadAC_Ohm', ...
        'MaximumNormalizedGain', 'MaximumGainFrequency_kHz', ...
        'FrequencyBelowResonance_kHz'});

%% PFM 调频控制小信号被控对象
% 在固定电阻负载下，由 FHA 稳态曲线求工作点增益斜率 Kvf。输出端
% 使用功率平衡线性化得到 tau = Rload*Cout/2。频率执行方向定义为
% fs = fs_bias - u，因此在正常负斜率工作区内，环路被控对象为正增益。
static_output_voltage_forward = Vin_forward .* gain_dc_forward;
static_output_voltage_reverse = Vin_reverse .* gain_dc_reverse;

