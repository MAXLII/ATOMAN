function plot_z2p2_closed_loop_bode( ...
    figure_title, frequency_hz, magnitude_db, phase_deg, ...
    power_w, load_resistance, plot_range_hz, curve_colors)
%PLOT_Z2P2_CLOSED_LOOP_BODE 绘制纯 2P2Z 闭环参考到输出频响。

    figure('Color', 'w', 'Name', figure_title);
    layout = tiledlayout(2, 1, 'TileSpacing', 'compact', ...
                         'Padding', 'compact');
    magnitude_axes = nexttile(layout, 1);
    phase_axes = nexttile(layout, 2);

    for axes_handle = [magnitude_axes, phase_axes]
        hold(axes_handle, 'on');
        grid(axes_handle, 'on');
        box(axes_handle, 'on');
        set(axes_handle, 'XScale', 'log');
        xlim(axes_handle, plot_range_hz);
    end

    for k = 1:numel(power_w)
        if ~any(isfinite(magnitude_db(:, k)))
            continue;
        end

        display_name = sprintf('%g W (%.3g Ohm)', ...
            power_w(k), load_resistance(k));
        semilogx(magnitude_axes, frequency_hz, magnitude_db(:, k), ...
            'LineWidth', 1.5, 'Color', curve_colors(k, :), ...
            'DisplayName', display_name);
        semilogx(phase_axes, frequency_hz, phase_deg(:, k), ...
            'LineWidth', 1.5, 'Color', curve_colors(k, :));
    end

    yline(magnitude_axes, -3, ':k', '-3 dB', ...
        'HandleVisibility', 'off');
    ylabel(magnitude_axes, 'Magnitude / dB');
    ylabel(phase_axes, 'Phase / degree');
    xlabel(phase_axes, 'Perturbation frequency / Hz');
    title(magnitude_axes, ...
        'G_{cl}(s) = G_{2P2Z}(s)G_{vf}(s) / [1 + G_{2P2Z}(s)G_{vf}(s)]');
    legend(magnitude_axes, 'Location', 'eastoutside');
    title(layout, figure_title);
end
