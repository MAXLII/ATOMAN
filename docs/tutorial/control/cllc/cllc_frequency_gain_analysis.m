%% 局部函数
function crossing_hz = find_gain_crossing( ...
    frequency_hz, gain, target, fr_hz, frequency_side)
%FIND_GAIN_CROSSING 查找最接近串联谐振点的目标增益交点。

    if strcmp(frequency_side, 'above')
        valid_index = find(frequency_hz >= fr_hz);
    elseif strcmp(frequency_side, 'below')
        valid_index = flip(find(frequency_hz <= fr_hz));
    else
        error('frequency_side must be ''above'' or ''below''.');
    end

    error_from_target = gain(valid_index) - target;
    crossing_pair = find( ...
        error_from_target(1:end-1) .* error_from_target(2:end) <= 0, ...
        1, 'first');

    if isempty(crossing_pair)
        crossing_hz = NaN;
        return;
    end

    index_1 = valid_index(crossing_pair);
    index_2 = valid_index(crossing_pair + 1);
    frequency_pair = frequency_hz([index_1, index_2]);
    gain_pair = gain([index_1, index_2]);

    if gain_pair(1) == gain_pair(2)
        crossing_hz = frequency_pair(1);
    else
        crossing_hz = frequency_pair(1) + ...
            (target - gain_pair(1)) * ...
            (frequency_pair(2) - frequency_pair(1)) / ...
            (gain_pair(2) - gain_pair(1));
    end
end

function [plant, Kvf, output_tau_s] = build_pfm_control_plant( ...
    control_frequency_hz, switching_frequency_hz, ...
    static_output_voltage, operating_frequency_hz, ...
    load_resistance, output_capacitance, delay_cycles)
%BUILD_PFM_CONTROL_PLANT 建立频率控制到输出电压的低频包络模型。
%
% 功率平衡线性化模型：
%   Gvf(s) = (-Kvf) / (1 + s*Rload*Cout/2) * exp(-s*Td)
%
% Kvf = dVout/dfs。负号来自 fs = fs_bias - controller_output 的执行
% 方向；Td 使用若干个开关周期近似数字更新和调制延迟。

    s = 1j .* 2 .* pi .* control_frequency_hz(:);
    load_count = numel(load_resistance);
    plant = complex(nan(numel(s), load_count));
    Kvf = nan(1, load_count);
    output_tau_s = load_resistance .* output_capacitance ./ 2;

    for k = 1:load_count
        if ~isfinite(operating_frequency_hz(k))
            continue;
        end

        voltage_slope = gradient( ...
            static_output_voltage(:, k), switching_frequency_hz(:));
        Kvf(k) = interp1( ...
            switching_frequency_hz, voltage_slope, ...
            operating_frequency_hz(k), 'linear');

        delay_s = delay_cycles / operating_frequency_hz(k);
        plant(:, k) = (-Kvf(k)) ./ ...
            (1 + s .* output_tau_s(k)) .* exp(-s .* delay_s);
    end
end

function [Kp, Ki, controller] = design_pi_controller( ...
    frequency_hz, design_plant, crossover_hz, zero_ratio)
%DESIGN_PI_CONTROLLER 按论文式 (16) 的零点比例和 0 dB 条件整定 PI。

    plant_gain_at_crossover = interp1( ...
        log10(frequency_hz), abs(design_plant), ...
        log10(crossover_hz), 'linear');
    zero_hz = zero_ratio .* crossover_hz;
    pi_shape_gain = sqrt(1 + (zero_hz / crossover_hz)^2);

    Kp = 1 / (plant_gain_at_crossover .* pi_shape_gain);
    Ki = 2 .* pi .* zero_hz .* Kp;

    s = 1j .* 2 .* pi .* frequency_hz(:);
    controller = Kp + Ki ./ s;
end

function [K, zero_hz, pole_hz, controller, selected_crossover_hz] = ...
    design_z2p2_controller( ...
        frequency_hz, design_plant, maximum_crossover_hz, ...
        design_output_tau_s, operating_frequency_hz, ...
        target_phase_margin_deg, target_gain_margin_db, ...
        minimum_crossover_ratio, max_pole_fs_ratio)
%DESIGN_Z2P2_CONTROLLER 设计与 code/lib/z2p2 参数形式一致的控制器。
%
% 连续域原型：
%   Gc(s) = K*(1+s/wz)^2 / (s*(1+s/wp)^2)
%
% 两个重合零点放在设计负载输出极点处。函数从 PI 的目标交越频率
% 向下搜索，选择同时满足 PM 和 GM 目标的最高交越频率。

    zero_hz = 1 ./ (2 .* pi .* design_output_tau_s);
    valid_operating_frequency_hz = operating_frequency_hz( ...
        isfinite(operating_frequency_hz));
    crossover_candidates_hz = logspace( ...
        log10(maximum_crossover_hz), ...
        log10(maximum_crossover_hz .* minimum_crossover_ratio), 41);

    for candidate_index = 1:numel(crossover_candidates_hz)
        candidate_crossover_hz = ...
            crossover_candidates_hz(candidate_index);
        [candidate_K, candidate_pole_hz, candidate_controller] = ...
            synthesize_z2p2_at_crossover( ...
                frequency_hz, design_plant, candidate_crossover_hz, ...
                zero_hz, valid_operating_frequency_hz, ...
                target_phase_margin_deg, max_pole_fs_ratio);

        candidate_loop = design_plant .* candidate_controller;
        [~, candidate_pm_deg, candidate_gm_db] = ...
            analyze_loop_margins(frequency_hz, candidate_loop);

        K = candidate_K;
        pole_hz = candidate_pole_hz;
        controller = candidate_controller;
        selected_crossover_hz = candidate_crossover_hz;

        if candidate_pm_deg >= target_phase_margin_deg && ...
           candidate_gm_db >= target_gain_margin_db
            return;
        end
    end
end

function [K, pole_hz, controller] = synthesize_z2p2_at_crossover( ...
    frequency_hz, design_plant, crossover_hz, zero_hz, ...
    valid_operating_frequency_hz, target_phase_margin_deg, ...
    max_pole_fs_ratio)
%SYNTHESIZE_Z2P2_AT_CROSSOVER 在指定交越频率下求 2P2Z 极点和增益。

    maximum_pole_hz = max(crossover_hz, ...
        max_pole_fs_ratio .* min(valid_operating_frequency_hz));
    plant_phase_deg = rad2deg(unwrap(angle(design_plant)));
    plant_phase_at_crossover_deg = interp1( ...
        log10(frequency_hz), plant_phase_deg, ...
        log10(crossover_hz), 'linear');
    required_controller_phase_deg = ...
        -180 + target_phase_margin_deg - ...
        plant_phase_at_crossover_deg;

    zero_phase_deg = 2 .* atand(crossover_hz ./ zero_hz);
    required_pole_angle_deg = ...
        (-90 + zero_phase_deg - required_controller_phase_deg) ./ 2;
    minimum_pole_angle_deg = atand(crossover_hz ./ maximum_pole_hz);
    pole_angle_deg = min(max(required_pole_angle_deg, ...
        minimum_pole_angle_deg), 45);
    pole_hz = crossover_hz ./ tand(pole_angle_deg);

    s = 1j .* 2 .* pi .* frequency_hz(:);
    base_controller = ...
        (1 + s ./ (2 .* pi .* zero_hz)).^2 ./ ...
        (s .* (1 + s ./ (2 .* pi .* pole_hz)).^2);
    plant_gain_at_crossover = interp1( ...
        log10(frequency_hz), abs(design_plant), ...
        log10(crossover_hz), 'linear');
    base_gain_at_crossover = interp1( ...
        log10(frequency_hz), abs(base_controller), ...
        log10(crossover_hz), 'linear');
    K = 1 ./ (plant_gain_at_crossover .* base_gain_at_crossover);
    controller = K .* base_controller;
end

function [crossover_hz, phase_margin_deg, gain_margin_db] = ...
    analyze_loop_margins(frequency_hz, loop_gain)
%ANALYZE_LOOP_MARGINS 计算每个负载下的交越频率、相位裕度和增益裕度。

    load_count = size(loop_gain, 2);
    crossover_hz = nan(1, load_count);
    phase_margin_deg = nan(1, load_count);
    gain_margin_db = nan(1, load_count);

    magnitude_db = 20 .* log10(abs(loop_gain));
    phase_deg = rad2deg(unwrap(angle(loop_gain), [], 1));

    for k = 1:load_count
        valid = isfinite(magnitude_db(:, k)) & ...
                isfinite(phase_deg(:, k));
        if nnz(valid) < 2
            continue;
        end

        frequency_valid = frequency_hz(valid);
        magnitude_valid = magnitude_db(valid, k);
        phase_valid = phase_deg(valid, k);

        gain_crossings_hz = find_log_crossings( ...
            frequency_valid, magnitude_valid, 0);
        if ~isempty(gain_crossings_hz)
            phase_at_crossings = interp1( ...
                log10(frequency_valid), phase_valid, ...
                log10(gain_crossings_hz), 'linear');
            phase_margins = 180 + phase_at_crossings;
            [phase_margin_deg(k), critical_crossing_index] = ...
                min(phase_margins);
            crossover_hz(k) = ...
                gain_crossings_hz(critical_crossing_index);
        end

        phase_crossings_hz = find_log_crossings( ...
            frequency_valid, phase_valid, -180);
        if ~isempty(phase_crossings_hz)
            magnitude_at_phase_crossings = interp1( ...
                log10(frequency_valid), magnitude_valid, ...
                log10(phase_crossings_hz), 'linear');
            gain_margin_db(k) = min(-magnitude_at_phase_crossings);
        else
            gain_margin_db(k) = Inf;
        end
    end
end

function crossings_hz = find_log_crossings(frequency_hz, value, target)
%FIND_LOG_CROSSINGS 在对数频率坐标中插值全部目标交点。

    difference = value - target;
    crossing_pairs = find( ...
        difference(1:end-1) .* difference(2:end) <= 0);

    if isempty(crossing_pairs)
        crossings_hz = [];
        return;
    end

    crossings_hz = nan(size(crossing_pairs));
    for k = 1:numel(crossing_pairs)
        crossing_pair = crossing_pairs(k);
        value_1 = value(crossing_pair);
        value_2 = value(crossing_pair + 1);
        log_frequency_1 = log10(frequency_hz(crossing_pair));
        log_frequency_2 = log10(frequency_hz(crossing_pair + 1));

        if value_1 == value_2
            crossings_hz(k) = 10^log_frequency_1;
        else
            interpolation_ratio = (target - value_1) / ...
                                  (value_2 - value_1);
            crossings_hz(k) = 10^(log_frequency_1 + ...
                interpolation_ratio * ...
                (log_frequency_2 - log_frequency_1));
        end
    end
end

function [bandwidth_hz, peak_db, peak_frequency_hz] = ...
    analyze_closed_loop_metrics(frequency_hz, closed_loop)
%ANALYZE_CLOSED_LOOP_METRICS 计算闭环 -3 dB 带宽和谐振峰值。

    load_count = size(closed_loop, 2);
    bandwidth_hz = nan(1, load_count);
    peak_db = nan(1, load_count);
    peak_frequency_hz = nan(1, load_count);

    magnitude_db = 20 .* log10(abs(closed_loop));
    for k = 1:load_count
        valid = isfinite(magnitude_db(:, k));
        if nnz(valid) < 2
            continue;
        end

        frequency_valid = frequency_hz(valid);
        magnitude_valid = magnitude_db(valid, k);
        [peak_db(k), peak_index] = max(magnitude_valid);
        peak_frequency_hz(k) = frequency_valid(peak_index);

        low_frequency_gain_db = magnitude_valid(1);
        bandwidth_target_db = low_frequency_gain_db - 3;
        post_peak_frequency_hz = frequency_valid(peak_index:end);
        post_peak_magnitude_db = magnitude_valid(peak_index:end);
        bandwidth_crossings_hz = find_log_crossings( ...
            post_peak_frequency_hz, post_peak_magnitude_db, ...
            bandwidth_target_db);
        if ~isempty(bandwidth_crossings_hz)
            bandwidth_hz(k) = bandwidth_crossings_hz(1);
        end
    end
end

